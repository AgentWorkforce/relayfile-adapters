import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import YAML from "yaml";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const mappingPath = fileURLToPath(
  new URL("../posthog.mapping.yaml", import.meta.url),
);
const outputPath = fileURLToPath(
  new URL("../src/resource-paths.generated.ts", import.meta.url),
);

const mapping = YAML.parse(await readFile(mappingPath, "utf8"));
const resources = mapping?.resources;
if (!resources || typeof resources !== "object" || Array.isArray(resources)) {
  throw new Error("posthog.mapping.yaml must define a resources object");
}

const paths = Object.fromEntries(
  Object.entries(resources)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, config]) => {
      const path = config?.path;
      if (typeof path !== "string" || path.length === 0) {
        throw new Error(`PostHog mapping resource ${name} must define path`);
      }
      return [name, path];
    }),
);

const content = `// Generated by scripts/generate-resource-paths.mjs. Do not edit.
export const POSTHOG_RESOURCE_PATHS = ${JSON.stringify(paths, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== content) {
    throw new Error(
      `PostHog resource paths are stale; run node ${packageRoot}/scripts/generate-resource-paths.mjs`,
    );
  }
} else {
  await writeFile(outputPath, content);
}
